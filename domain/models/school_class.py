# ? کلاس یا گروه آموزشی که یک معلم چند دانش‌آموز را در آن مدیریت می‌کند.
# ? این موجودیت عمداً بسیار ساده نگه داشته شده - فقط برای گروه‌بندی دانش‌آموزان
# ? و محاسبه میانگین/مقایسه در سطح کلاس (که در فاز Analytics پیاده می‌شود).

import uuid

from pydantic import BaseModel, Field


class SchoolClass(BaseModel):
    """? یک کلاس/گروه آموزشی - مثلاً «هفتم الف»."""

    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    name: str = Field(min_length=1)

    # ? اختیاری - برای تفکیک کلاس‌های هم‌نام در سال‌های تحصیلی مختلف.
    academic_year: str | None = Field(default=None)
