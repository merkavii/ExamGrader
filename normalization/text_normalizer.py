# ? حتی در ورودی دستی معلم، ممکن است کیبورد فارسی/عربی/ویندوز حروف مشابه ولی
# ? یونیکد متفاوت تولید کند (مثلاً "ي" عربی به‌جای "ی" فارسی). این تفاوت ظاهراً
# ? نامرئی است ولی در مقایسه رشته‌ای (مثلاً Short Answer Grader) باعث خطای
# ? نمره‌دهی می‌شود. این ماژول این مشکل را در همان لایه ورودی حل می‌کند.

# ? نگاشت کاراکترهای عربی به معادل فارسی رایج آن‌ها
_ARABIC_TO_PERSIAN_CHARS = {
    "ي": "ی",
    "ك": "ک",
    "ة": "ه",
    "ؤ": "و",
    "إ": "ا",
    "أ": "ا",
}


def normalize_text(raw_text: str) -> str:
    """
    ? ورودی خام معلم/دانش‌آموز را استاندارد می‌کند:
    ? - حذف فاصله‌های اضافه ابتدا/انتها و فاصله‌های تکراری وسط متن
    ? - یکسان‌سازی کاراکترهای عربی به معادل فارسی

    ! این تابع معنای متن را تغییر نمی‌دهد - فقط نمایش یکنواخت آن را تضمین می‌کند.
    """
    normalized = raw_text.strip()
    for arabic_char, persian_char in _ARABIC_TO_PERSIAN_CHARS.items():
        normalized = normalized.replace(arabic_char, persian_char)

    # ? فشرده‌سازی چند فاصله پشت‌سرهم به یک فاصله
    normalized = " ".join(normalized.split())
    return normalized
