# ? برخلاف Essay، پاسخ کوتاه Rubric ندارد - فقط باید تشخیص داده شود که آیا
# ? پاسخ دانش‌آموز از نظر معنایی با پاسخ مرجع یکی است یا نه (حتی اگر کلمه‌به‌کلمه
# ? یکسان نباشد؛ مثلاً "تهران" و "شهر تهران" باید هر دو درست باشند).


def build_short_answer_grading_prompt(
    question_text: str,
    reference_answer: str,
    student_answer: str,
) -> str:
    return f"""تو یک دستیار تصحیح آزمون هستی. باید تشخیص بدهی آیا پاسخ کوتاه دانش‌آموز
از نظر معنایی با پاسخ صحیح یکی است یا نه - حتی اگر عبارت‌بندی دقیقاً یکسان نباشد.

سؤال:
{question_text}

پاسخ صحیح:
{reference_answer}

پاسخ دانش‌آموز:
{student_answer}

فقط و فقط یک JSON با دقیقاً این ساختار برگردان، بدون هیچ متن اضافه قبل یا بعد آن:

{{
  "is_correct": true یا false,
  "reasoning": "توضیح کوتاه فارسی درباره دلیل تصمیم",
  "confidence": عدد بین ۰ تا ۱۰۰
}}"""
